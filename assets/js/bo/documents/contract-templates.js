    const thaiDate = (iso) => {
        if (!iso || !/^\d{4}-\d{2}-\d{2}$/.test(iso)) return '';
        const [y, m, d] = iso.split('-').map(Number);
        return `${d} ${MONTHS[m - 1]} พ.ศ. ${y + 543}`;
    };
    const fmt = (n) => Number(n).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });

    function bahtText(num) {
        const n = Math.round(Number(num) * 100) / 100;
        if (!isFinite(n) || n <= 0) return '';
        const D = ['ศูนย์', 'หนึ่ง', 'สอง', 'สาม', 'สี่', 'ห้า', 'หก', 'เจ็ด', 'แปด', 'เก้า'];
        const U = ['', 'สิบ', 'ร้อย', 'พัน', 'หมื่น', 'แสน'];
        const read = (s) => {
            let out = '';
            const len = s.length;
            for (let i = 0; i < len; i++) {
                const d = Number(s[i]);
                const pos = len - i - 1;
                if (d === 0) continue;
                if (pos === 0 && d === 1 && len > 1) out += 'เอ็ด';
                else if (pos === 1 && d === 2) out += 'ยี่สิบ';
                else if (pos === 1 && d === 1) out += 'สิบ';
                else out += D[d] + U[pos];
            }
            return out;
        };
        const readBig = (int) => {
            let s = String(int), out = '';
            while (s.length > 6) { out = read(s.slice(-6)) + 'ล้าน' + out; s = s.slice(0, -6); }
            return read(s) + out;
        };
        const [i, f] = n.toFixed(2).split('.');
        let t = (Number(i) ? readBig(i) + 'บาท' : '');
        t += Number(f) ? read(f) + 'สตางค์' : 'ถ้วน';
        return t;
    }

