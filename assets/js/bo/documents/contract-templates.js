    function warnings(type, f) {
        const t = TYPES[type];
        const w = t && t.warn ? t.warn(f) : [];
        const miss = [];
        if (!String(f.aName || '').trim()) miss.push(`ยังไม่ได้ระบุชื่อ${t ? t.roles.a : 'คู่สัญญา'}`);
        if (!String(f.bName || '').trim()) miss.push(`ยังไม่ได้ระบุชื่อ${t ? t.roles.b : 'คู่สัญญา'}`);
        return miss.concat(w);
    }

    // The counterparty (non-Kitten side) and contract value, for the register.
    function summary(type, f) {
        const t = TYPES[type] || TYPES.service;
        const other = t.kittenSide === 'a' ? 'b' : 'a';
        const value = Number(f.total) || Number(f.salary) || Number(f.estimate) || 0;
        return { party: String(f[other + 'Name'] || '').trim(), amountTotal: value, subject: f.subject || f.project || f.position || f.purpose || '' };
    }

